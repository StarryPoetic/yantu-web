export function normalizeCitySearch(value: string): string {
  return value
    .trim()
    .toLocaleLowerCase()
    .replace(/[\s'’·-]/g, "")
    .replace(/ü/g, "v");
}

export function searchCities(query: string): CityOption[] {
  const search = normalizeCitySearch(query);
  if (!search) return CITY_OPTIONS;
  return CITY_OPTIONS.filter(
    (city) =>
      city.name.includes(search) ||
      city.province.includes(search) ||
      (city.name + "市").includes(search) ||
      city.pinyin.includes(search) ||
      city.initials.startsWith(search),
  );
}

export function normalizeCityName(value: string): string {
  const trimmed = value.trim();
  const known = CITY_OPTIONS.find(
    (city) => city.name === trimmed || city.name + "市" === trimmed,
  );
  return known?.name ?? trimmed;
}
